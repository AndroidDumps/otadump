#[cfg(otadump_zucchini)]
fn brotli_compress(bytes: &[u8]) -> Vec<u8> {
    let mut compressed = Vec::new();
    {
        let mut writer = brotli::CompressorWriter::new(&mut compressed, 4096, 9, 20);
        writer.write_all(bytes).unwrap();
    }
    compressed
}

