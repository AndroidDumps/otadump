#[derive(Clone, PartialEq, Message)]
struct Extent {
    #[prost(uint64, optional, tag = "1")]
    start_block: Option<u64>,
    #[prost(uint64, optional, tag = "2")]
    num_blocks: Option<u64>,
}

#[derive(Clone, PartialEq, Message)]
struct PartitionInfo {
    #[prost(uint64, optional, tag = "1")]
    size: Option<u64>,
    #[prost(bytes = "vec", optional, tag = "2")]
    hash: Option<Vec<u8>>,
}

#[derive(Clone, PartialEq, Message)]
struct InstallOperation {
    #[prost(int32, tag = "1")]
    operation_type: i32,
    #[prost(uint64, optional, tag = "2")]
    data_offset: Option<u64>,
    #[prost(uint64, optional, tag = "3")]
    data_length: Option<u64>,
    #[prost(message, repeated, tag = "4")]
    src_extents: Vec<Extent>,
    #[prost(uint64, optional, tag = "5")]
    src_length: Option<u64>,
    #[prost(message, repeated, tag = "6")]
    dst_extents: Vec<Extent>,
    #[prost(uint64, optional, tag = "7")]
    dst_length: Option<u64>,
    #[prost(bytes = "vec", optional, tag = "8")]
    data_sha256_hash: Option<Vec<u8>>,
    #[prost(bytes = "vec", optional, tag = "9")]
    src_sha256_hash: Option<Vec<u8>>,
}

#[derive(Clone, PartialEq, Message)]
struct PartitionUpdate {
    #[prost(string, tag = "1")]
    partition_name: String,
    #[prost(message, optional, tag = "6")]
    old_partition_info: Option<PartitionInfo>,
    #[prost(message, optional, tag = "7")]
    new_partition_info: Option<PartitionInfo>,
    #[prost(message, repeated, tag = "8")]
    operations: Vec<InstallOperation>,
    #[prost(message, optional, tag = "10")]
    hash_tree_data_extent: Option<Extent>,
    #[prost(message, optional, tag = "11")]
    hash_tree_extent: Option<Extent>,
    #[prost(string, optional, tag = "12")]
    hash_tree_algorithm: Option<String>,
    #[prost(bytes = "vec", optional, tag = "13")]
    hash_tree_salt: Option<Vec<u8>>,
    #[prost(message, optional, tag = "14")]
    fec_data_extent: Option<Extent>,
    #[prost(message, optional, tag = "15")]
    fec_extent: Option<Extent>,
    #[prost(uint32, optional, tag = "16")]
    fec_roots: Option<u32>,
}

#[derive(Clone, PartialEq, Message)]
struct DeltaArchiveManifest {
    #[prost(uint32, optional, tag = "3")]
    block_size: Option<u32>,
    #[prost(uint32, optional, tag = "12")]
    minor_version: Option<u32>,
    #[prost(message, repeated, tag = "13")]
    partitions: Vec<PartitionUpdate>,
}

#[derive(Clone, Copy, PartialEq, Message)]
struct Lz4diffAlgorithm {
    #[prost(int32, tag = "1")]
    algorithm_type: i32,
    #[prost(int32, tag = "2")]
    level: i32,
}

#[derive(Clone, PartialEq, Message)]
struct Lz4diffBlock {
    #[prost(uint64, tag = "1")]
    uncompressed_offset: u64,
    #[prost(uint64, tag = "2")]
    uncompressed_length: u64,
    #[prost(uint64, tag = "3")]
    compressed_length: u64,
    #[prost(bytes = "vec", tag = "4")]
    sha256_hash: Vec<u8>,
    #[prost(bytes = "vec", tag = "5")]
    postfix_bspatch: Vec<u8>,
}

#[derive(Clone, PartialEq, Message)]
struct Lz4diffCompressionInfo {
    #[prost(message, optional, tag = "1")]
    algo: Option<Lz4diffAlgorithm>,
    #[prost(message, repeated, tag = "2")]
    block_info: Vec<Lz4diffBlock>,
    #[prost(bool, tag = "3")]
    zero_padding_enabled: bool,
}

#[derive(Clone, PartialEq, Message)]
struct Lz4diffHeader {
    #[prost(message, optional, tag = "1")]
    src_info: Option<Lz4diffCompressionInfo>,
    #[prost(message, optional, tag = "2")]
    dst_info: Option<Lz4diffCompressionInfo>,
    #[prost(int32, tag = "3")]
    inner_type: i32,
}

fn sha256(bytes: &[u8]) -> Vec<u8> {
    digest::digest(&digest::SHA256, bytes).as_ref().to_vec()
}

